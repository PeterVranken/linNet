function [tf_SIMO deviceConstants wBode tiStep] = SIMO(deviceConstants)

%   [tf deviceConstants wBode tiStep] = SIMO(deviceConstants)
%                   The transfer function SIMO of electric linear network
%                   testCases\useCaseOpFilter\useCaseOpFilter.cnl
%
%   Input argument(s):
%       deviceConstants
%                   The values of the device constants packed into a
%                   struct. These values are used to create tf. If the
%                   argument is omitted then the device values from the
%                   circuit file are used
%   Return argument(s):
%       tf          The transfer function object
%       deviceConstants
%                   The values of all device constants packed into a
%                   struct. These are the values, which have been used to
%                   create tf
%       wBode       A vector of frequency values (unit: rad/s), which can be
%                   passed together with tf to a frequency domain function
%                   like bode or nyquist. The values are derived from a plot
%                   information in the circuit file. wBode is the empty
%                   vector if no plot information was specified
%       tiStep      A vector of time values (unit: s), which can be passed
%                   together with tf to a time domain function like step or
%                   impulse. The values are derived from a plot information in
%                   the circuit file. tiStep is the empty vector if no plot
%                   information was specified
%
%   Example(s):
%       SIMO
%                   Plot the transfer or step function as defined in the
%                   circuit file
%       [tf_SIMO p] = SIMO
%                   Get a TF object and the default set of device constants
%       p.R1 = 2*p.R2
%                   (Modify the device constants in p)
%       step(SIMO(p))
%                   Plot the step response of the system with modified device
%                   constants
