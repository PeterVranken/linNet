              + R2*R3*R5*R6*C1*C3 ...
             )	 % s^2
           ; (R1*R2*R4*C1 + R1*R3*R4*C1 + R1*R4*R5*C3 + R1*R4*R6*C3 + R1*R5*R6*C3 ...
              + R2*R3*R4*C1 ...
             )	 % s^1
